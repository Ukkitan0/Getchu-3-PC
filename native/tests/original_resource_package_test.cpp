using namespace ae3;
static void put32(std::vector<std::byte>& p, std::size_t at, std::uint32_t x) {
    for (int j=0;j<4;++j) p.at(at+j)=std::byte((x>>(8*j))&255);
}
static void putText(std::vector<std::byte>& p, std::size_t at, const char* s) {
    while (*s) p.at(at++)=std::byte(static_cast<unsigned char>(*s++));
}
static void ck(bool test, const char* msg) { if (!test) throw std::runtime_error(msg); }
template<class F> static void rejects(F fn) {
    bool failed=false;
    try { fn(); } catch (const std::exception&) { failed=true; }
    ck(failed,"truncated/invalid PCK was accepted");
}
static std::vector<std::byte> sample() {
    // Original EXDB container offsets validated by private woods_c fixture:
    // entries at 0x40, first payload 0x60 (0x1400), second at 0x1460.
    // Reproduce *structure* with generated bytes, not retail content.
    std::vector<std::byte> bytes(0x1660);
    putText(bytes,0,"PCK");put32(bytes,4,0x40);put32(bytes,8,2);
    putText(bytes,0x10,"monkeyprofile.exdb");   // length 18 + NUL
    putText(bytes,0x23,"exdb");
    putText(bytes,0x28,"MainCameraParam.exdb");
    put32(bytes,0x40,0x10);put32(bytes,0x44,0x23);
    put32(bytes,0x48,0x60);put32(bytes,0x4c,0x1400);
    put32(bytes,0x50,0x28);put32(bytes,0x54,0x23);
    put32(bytes,0x58,0x1460);put32(bytes,0x5c,0x200);
    putText(bytes,0x60,"EDB\n");putText(bytes,0x1460,"EDB\n");
    return bytes;
}
int main() {
    try {
        const auto bytes=sample();
        OriginalPckResourcePackage pck(bytes);
        ck(pck.entries().size()==2,"actual 16-byte source item count");
        ck(pck.entries()[0].name=="monkeyprofile.exdb","source name 0");
        ck(pck.entries()[1].name=="MainCameraParam.exdb","source name 1");
        ck(pck.entries()[0].type=="exdb"&&pck.entries()[1].type=="exdb","source type string");
        ck(pck.entries()[0].payloadOffset==0x60 && pck.entries()[0].payload.size()==0x1400,"original source offset 0");
        ck(pck.entries()[1].payloadOffset==0x1460 && pck.entries()[1].payload.size()==0x200,"original source offset 1");
        ck(pck.require("MainCameraParam.exdb","exdb").sourceIndex==1,"exact name/type lookup");
        ck(!pck.first("maincameraparam.exdb","exdb"),"source name comparison must be exact");
        ck(pck.selectType_26d24c("exdb")==std::vector<std::size_t>({0,1}),"retail type dispatch");
        ck(originalPckPayloadSignature(pck.entries()[0].payload)==OriginalPckPayloadSignature::exdb,"source EXDB signature");
        ck(originalPckRetailTypeMatch_26d2b8("exdb private","exdb"),"space suffix accepted");
        ck(!originalPckRetailTypeMatch_26d2b8("exdb2","exdb"),"raw prefix rejected");
        ck(originalPckRetailTypeMatch_26d2b8("exdb","exdb"),"exact suffix accepted");
        // A resource view stays valid while its immovable package lives.
        const auto view=pck.require("monkeyprofile.exdb","exdb");
        ck(view.payload.data()>=pck.originalPackageBytes().data() &&
           view.payload.data()<pck.originalPackageBytes().data()+pck.originalPackageBytes().size(),
           "view must address owned bytes");
        rejects([&]{auto data=bytes;put32(data,4,0xfffffff0);OriginalPckResourcePackage x(std::move(data));});
        rejects([&]{auto data=bytes;put32(data,0x40,0);OriginalPckResourcePackage x(std::move(data));});
        rejects([&]{auto data=bytes;put32(data,0x50,0x3f);OriginalPckResourcePackage x(std::move(data));});
        rejects([&]{auto data=bytes;put32(data,0x48,0x50);OriginalPckResourcePackage x(std::move(data));});
        rejects([&]{auto data=bytes;put32(data,0x4c,0xffffffff);OriginalPckResourcePackage x(std::move(data));});
        rejects([&]{auto data=bytes;put32(data,8,0xffffffff);OriginalPckResourcePackage x(std::move(data));});
        rejects([&]{auto data=bytes;for(int i=0x23;i<0x40;++i)data[i]=std::byte{'X'};
                      OriginalPckResourcePackage x(std::move(data));});
        // Signature dispatch is content-based, NOT based on invented file extensions.
        const std::array<std::pair<const char*,OriginalPckPayloadSignature>,4> signatures{{
           {"I3D_BIN",OriginalPckPayloadSignature::i3d_mesh},
           {"I3D_I3M",OriginalPckPayloadSignature::i3d_animation},
           {"I3D_I3C",OriginalPckPayloadSignature::i3d_collision},
           {"TIM2",OriginalPckPayloadSignature::tim2}
        }};
        for (auto [s,expected]:signatures) {
            std::vector<std::byte> raw;
            for (auto p=s;*p;++p)raw.push_back(std::byte(static_cast<unsigned char>(*p)));
            if (raw.size()==7) raw.push_back(std::byte{0}); // Original 8-byte I3D signature field.
            ck(originalPckPayloadSignature(raw)==expected,"original resource magic");
        }
        std::cout << "ORIGINAL_RESOURCE_PACKAGE_TEST_PASSED members=2 malformed=7 signatures=5\n";
        return 0;
    } catch (const std::exception& e) {
        std::cerr << "ORIGINAL_RESOURCE_PACKAGE_TEST_FAILED: " << e.what() << '\n';
        return 1;
    }
}
