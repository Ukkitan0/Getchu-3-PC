namespace ae3 {
class OriginalStageActorNavigation_57c7cc;

// Host-native lifetime boundary between recovered original 0x2207D0
// source routes and original 0x57C7CC actor route following. This
// adapter is NOT a recovered original EE actor/controller structure.
// The stage owners MUST outlive this binding. For grouped routes, the
// source group may be destroyed independently (weak lifetime guard).
class OriginalNavActorRouteBinding final {
public:
    explicit OriginalNavActorRouteBinding(
        const OriginalNavStageOwners_21ed30& owners) noexcept
        :owners_(owners) {}
    OriginalNavActorRouteBinding(const OriginalNavActorRouteBinding&)=delete;
    OriginalNavActorRouteBinding& operator=(const OriginalNavActorRouteBinding&)=delete;

    // The original path is generated by the existing retail-derived
    // dispatcher, not by this class.
    void originalUseStageRoute_2207d0(OriginalNavStageRouteSnapshot route);
    void originalUseGroupRoute_2207d0(
        const OriginalNavStageGroupSession& originalGroupOwner,
        OriginalNavStageGroupedRoute route);

    // Original 0x57C7CC targets point INTO the live owner's 0x70-byte
    // records; dropping the owner invalidates controller target+0x50.
    bool originalRouteCurrent() const noexcept;
    bool originalDropInvalidRoute() noexcept;
    void originalClearForStageTransition() noexcept;
    const OriginalSpatialRecord70* originalCurrentTargetAt50() const noexcept;
    std::size_t originalPathLength() const noexcept;
    bool originalHasMultiplePolygonsAtController1c() const noexcept;

    // Reuses original 0x221104/0x21B444/0x57BD88 and 0x57BDB8.
    OriginalActorRouteEdgeDecision_57bd88 originalCurrentEdge_57bd88(
        std::size_t sourceSegmentIndex) const;
    std::optional<OriginalActorType2Target_57bdb8>
        originalInitialType2Target_57bdb8() const;

    // Directly forwards the ORIGINAL route to the existing physics-owned
    // original stage actor pipeline, rather than inventing controller
    // movement. The caller must supply the exact stage source graph from
    // which that pipeline was constructed; the VU0 team should expose a
    // read-only identity accessor to make that check intrinsic.
    OriginalActorRouteFollowResult_57c7cc originalAdvanceNativeStage_57c7cc(
        OriginalStageActorNavigation_57c7cc& originalActorPipeline,
        const OriginalStageSpatialLoaded& sourceGraphUsedByPipeline,
        std::uint32_t originalActorStagePolygonIndex);

    // Source callbacks are provided by the VU0/physics implementation;
    // no replacement projection or update target is installed.
    OriginalActorRouteFollowResult_57c7cc originalAdvance_57c7cc(
        std::uint32_t originalActorPolygonIndex,
        OriginalActorRouteFollowerCalls_57c7cc& originalSourceCalls);
private:
    const OriginalNavStageRouteSnapshot& currentRouteOrThrow() const;
    const OriginalNavStageOwners_21ed30& owners_;
    std::optional<OriginalNavStageRouteSnapshot> plainRoute_;
    std::optional<OriginalNavStageGroupedRoute> groupRoute_;
    const OriginalNavStageGroupSession* groupOwner_=nullptr;
    std::weak_ptr<const std::uint8_t> groupLifetime_;
    const OriginalSpatialRecord70* currentTargetAt50_=nullptr;
};
} // namespace ae3
