#ifndef AE3_BOOT_SEMAPHORE_INIT_H
#define AE3_BOOT_SEMAPHORE_INIT_H
#include "ae3_boot_init_prefix.h"
/* Retail chain: 0x43FE60 calls 0x43FC08, which creates two EE semaphores
   using the 0x435AE0 kernel wrapper (syscall 0x40). The game is stopped at
   its NEXT JAL (0x43FE68); a simulated CreateSema response is opt-in. */
#define AE3_SEMA_INIT_CALL_PC UINT32_C(0x0043FE60)
#define AE3_SEMA_ROUTINE_PC UINT32_C(0x0043FC08)
#define AE3_SEMA_SYSCALL_WRAPPER UINT32_C(0x00435AE0)
#define AE3_SEMA_SYSCALL_PC UINT32_C(0x00435AE4)
#define AE3_SEMA_NEXT_CALL_PC UINT32_C(0x0043FE68)

typedef enum AE3_SemaBootResult {
    AE3_SEMA_YIELDED=1, AE3_SEMA_CREATE_REQUEST=2,
    AE3_SEMA_NEXT_CALL=3, AE3_SEMA_MEMORY_FAULT=-1,
    AE3_SEMA_UNSUPPORTED=-2, AE3_SEMA_INVALID=-3
} AE3_SemaBootResult;
typedef struct AE3_GuestSemaRequest {
    uint32_t syscall_number, pc, guest_address;
    /* ee_sema_t layout: count, max_count, init_count, wait_threads, attr, option */
    uint32_t values[6];
} AE3_GuestSemaRequest;
typedef struct AE3_BootSemaphoreInit {
    AE3_BootPrefix cpu;
    AE3_GuestSemaRequest request;
    uint8_t pending;
    uint8_t completed;
    uint8_t done;
} AE3_BootSemaphoreInit;

AE3_SemaBootResult ae3_boot_sema_enter(AE3_BootSemaphoreInit *out,
                                      const AE3_BootInitPrefix *init);
AE3_SemaBootResult ae3_boot_sema_slice(AE3_BootSemaphoreInit *s,
                                      uint8_t *ram, size_t ram_bytes,
                                      uint32_t instruction_budget);
/* A return from an external EE kernel implementation. It may be a failure
   (negative ID) and is NOT generated by this instruction interpreter. */
AE3_SemaBootResult ae3_boot_sema_kernel_return(AE3_BootSemaphoreInit *s,
                                               int32_t kernel_result);
#endif